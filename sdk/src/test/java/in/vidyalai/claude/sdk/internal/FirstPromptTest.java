package in.vidyalai.claude.sdk.internal;

import static org.assertj.core.api.Assertions.assertThat;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;

import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.databind.ObjectMapper;

import in.vidyalai.claude.sdk.types.session.SessionKey;
import in.vidyalai.claude.sdk.types.session.SessionStoreEntry;
import in.vidyalai.claude.sdk.types.session.SessionSummary;
import in.vidyalai.claude.sdk.types.session.SessionSummaryEntry;

/**
 * First-prompt extraction, ported from the Python SDK's
 * {@code _extract_first_prompt_from_head} / {@code _fold_first_prompt} and
 * their tests. The disk head scan and the SessionStore fold share one
 * implementation, so the fold cases at the end must agree with the head scan.
 */
class FirstPromptTest {

    private static final ObjectMapper MAPPER = new ObjectMapper();

    private static String line(Map<String, Object> entry) {
        try {
            return MAPPER.writeValueAsString(entry);
        } catch (JsonProcessingException e) {
            throw new IllegalStateException(e);
        }
    }

    private static Map<String, Object> user(Object content) {
        Map<String, Object> entry = new LinkedHashMap<>();
        entry.put("type", "user");
        entry.put("message", Map.of("content", content));
        return entry;
    }

    @SafeVarargs
    private static String head(Map<String, Object>... entries) {
        StringBuilder sb = new StringBuilder();
        for (Map<String, Object> e : entries) {
            sb.append(line(e)).append('\n');
        }
        return sb.toString();
    }

    private static Map<String, Object> textBlock(String text) {
        return Map.of("type", "text", "text", text);
    }

    // ---------------------------------------------------------------------
    // Ported from Python tests/test_sessions.py
    // ---------------------------------------------------------------------

    @Test
    void simple() {
        assertThat(FirstPrompt.extractFromHead(head(user("Hello!")))).isEqualTo("Hello!");
    }

    @Test
    void skipsMeta() {
        Map<String, Object> meta = user("meta");
        meta.put("isMeta", true);
        assertThat(FirstPrompt.extractFromHead(head(meta, user("real prompt")))).isEqualTo("real prompt");
    }

    @Test
    void skipsToolResult() {
        Map<String, Object> toolResult = user(List.of(Map.of("type", "tool_result", "content", "x")));
        assertThat(FirstPrompt.extractFromHead(head(toolResult, user("actual prompt"))))
                .isEqualTo("actual prompt");
    }

    @Test
    void contentBlocks() {
        assertThat(FirstPrompt.extractFromHead(head(user(List.of(textBlock("block prompt"))))))
                .isEqualTo("block prompt");
    }

    @Test
    void truncates() {
        String result = FirstPrompt.extractFromHead(head(user("x".repeat(300))));
        assertThat(result).hasSize(201);
        assertThat(result).endsWith("\u2026");
    }

    @Test
    void commandFallback() {
        assertThat(FirstPrompt.extractFromHead(head(user("<command-name>/help</command-name>stuff"))))
                .isEqualTo("/help");
    }

    @Test
    void empty() {
        assertThat(FirstPrompt.extractFromHead("")).isEmpty();
        assertThat(FirstPrompt.extractFromHead("{\"type\":\"assistant\"}\n")).isEmpty();
    }

    // ---------------------------------------------------------------------
    // Skip pattern (Python _SKIP_FIRST_PROMPT_PATTERN)
    // ---------------------------------------------------------------------

    @ParameterizedTest
    @ValueSource(strings = {
            "<local-command-stdout>output</local-command-stdout>",
            "<session-start-hook>hook output",
            "<tick>",
            "<goal>ship it</goal>",
            "[Request interrupted by user]",
            "[Request interrupted by user for tool use]",
            "<ide_opened_file>The user opened a.txt</ide_opened_file>",
            "  <ide_selection>selected\nlines</ide_selection>  ",
    })
    void skipsAutoGeneratedText(String text) {
        assertThat(FirstPrompt.extractFromHead(head(user(text), user("real")))).isEqualTo("real");
    }

    @ParameterizedTest
    @ValueSource(strings = {
            "<local-command-stderr>err</local-command-stderr>",
            "<bash-input>ls</bash-input>",
            "<bash-stdout>out</bash-stdout>",
            "<local-command-control>x</local-command-control>",
    })
    void keepsTextPythonDoesNotSkip(String text) {
        assertThat(FirstPrompt.extractFromHead(head(user(text), user("later")))).isEqualTo(text);
    }

    @Test
    void ideTagFollowedByAQuestionIsAPrompt() {
        String text = "<ide_opened_file>a.txt</ide_opened_file> what does this do?";
        assertThat(FirstPrompt.extractFromHead(head(user(text)))).isEqualTo(text);
    }

    // ---------------------------------------------------------------------
    // Command fallback, isCompactSummary, newlines, blocks, truncation
    // ---------------------------------------------------------------------

    @Test
    void commandTagAnywhereIsSkippedAndRemembered() {
        // Not starting with "/": the fallback still applies (Python searches).
        String cmd = "<command-message>review</command-message>\n<command-name>/review</command-name>";
        assertThat(FirstPrompt.extractFromHead(head(user(cmd)))).isEqualTo("/review");
        assertThat(FirstPrompt.extractFromHead(head(user(cmd), user("then this")))).isEqualTo("then this");
    }

    @Test
    void firstCommandWinsTheFallback() {
        assertThat(FirstPrompt.extractFromHead(head(
                user("<command-name>/one</command-name>"),
                user("<command-name>/two</command-name>"))))
                .isEqualTo("/one");
    }

    @Test
    void slashTextWithoutCommandTagIsAPrompt() {
        assertThat(FirstPrompt.extractFromHead(head(user("/help me with this")))).isEqualTo("/help me with this");
    }

    @Test
    void skipsIsCompactSummaryButNotIsCompact() {
        Map<String, Object> summary = user("compact summary");
        summary.put("isCompactSummary", true);
        assertThat(FirstPrompt.extractFromHead(head(summary, user("real")))).isEqualTo("real");

        Map<String, Object> compact = user("kept");
        compact.put("isCompact", true);
        assertThat(FirstPrompt.extractFromHead(head(compact))).isEqualTo("kept");
    }

    @Test
    void collapsesNewlinesAndStrips() {
        assertThat(FirstPrompt.extractFromHead(head(user("  line one\nline two\n"))))
                .isEqualTo("line one line two");
    }

    @Test
    void stripsUnicodeWhitespaceLikePython() {
        assertThat(FirstPrompt.extractFromHead(head(user("\u00a0hello\u202f")))).isEqualTo("hello");
        assertThat(FirstPrompt.extractFromHead(head(user("\u00a0\u2007"), user("next")))).isEqualTo("next");
    }

    @Test
    void triesEveryTextBlock() {
        Map<String, Object> entry = user(List.of(
                textBlock("<ide_selection>code</ide_selection>"),
                Map.of("type", "image"),
                textBlock("   "),
                textBlock("explain the selection")));
        assertThat(FirstPrompt.extractFromHead(head(entry))).isEqualTo("explain the selection");
    }

    @Test
    void rstripsBeforeTheEllipsis() {
        String text = "x".repeat(198) + "   " + "y".repeat(50);
        assertThat(FirstPrompt.extractFromHead(head(user(text)))).isEqualTo("x".repeat(198) + "\u2026");
    }

    @Test
    void truncatesByCodePoints() {
        String emoji = "\uD83D\uDE00"; // one code point, two UTF-16 units
        String result = FirstPrompt.extractFromHead(head(user(emoji.repeat(250))));
        assertThat(result).isEqualTo(emoji.repeat(200) + "\u2026");
    }

    @Test
    void textMentioningToolUseIdIsStillAPrompt() {
        String text = "why is tool_use_id missing?";
        assertThat(FirstPrompt.extractFromHead(head(user(text)))).isEqualTo(text);
    }

    @Test
    void acceptsSpacedTypeAndRejectsConcatenatedObjects() {
        String spaced = "{\"type\": \"user\", \"message\": {\"content\": \"spaced\"}}\n";
        assertThat(FirstPrompt.extractFromHead(spaced)).isEqualTo("spaced");

        String concatenated = line(user("first")) + line(user("second")) + "\n" + line(user("third")) + "\n";
        assertThat(FirstPrompt.extractFromHead(concatenated)).isEqualTo("third");
    }

    @Test
    void userWordElsewhereDoesNotMakeALineAUserEntry() {
        // Python's pre-check needs "type":"user", not just "user" anywhere.
        String h = "{\"type\":\"assistant\",\"role\":\"user\",\"message\":{\"content\":\"no\"}}\n"
                + line(user("yes")) + "\n";
        assertThat(FirstPrompt.extractFromHead(h)).isEqualTo("yes");
    }

    // ---------------------------------------------------------------------
    // The SessionStore fold shares the implementation
    // ---------------------------------------------------------------------

    private static SessionSummaryEntry fold(List<Map<String, Object>> entries) {
        List<SessionStoreEntry> wrapped = new ArrayList<>();
        for (Map<String, Object> e : entries) {
            wrapped.add(SessionStoreEntry.of(e));
        }
        return SessionSummary.foldSessionSummary(
                null, SessionKey.main("proj", "12345678-1234-1234-1234-123456789abc"), wrapped);
    }

    @Test
    void foldUsesTheSameSkipPatternAndRules() {
        SessionSummaryEntry s = fold(List.of(
                user("<tick>"),
                user("[Request interrupted by user]"),
                user(List.of(textBlock("<ide_opened_file>f</ide_opened_file>"), textBlock("real\nprompt")))));
        assertThat(s.data()).containsEntry("first_prompt", "real prompt");

        SessionSummaryEntry kept = fold(List.of(user("<local-command-stderr>e</local-command-stderr>")));
        assertThat(kept.data()).containsEntry("first_prompt", "<local-command-stderr>e</local-command-stderr>");

        SessionSummaryEntry cmd = fold(List.of(user("<command-message>x</command-message><command-name>/x</command-name>")));
        assertThat(cmd.data()).containsEntry("command_fallback", "/x").doesNotContainKey("first_prompt");
    }

    @Test
    void foldAgreesWithHeadScan() {
        List<String> texts = List.of(
                "<session-start-hook>x",
                "<goal>g</goal>",
                "  padded\u00a0",
                "x".repeat(198) + "   " + "y".repeat(50),
                "\uD83D\uDE00".repeat(201));
        for (String text : texts) {
            Object folded = fold(List.of(user(text), user("fallthrough"))).data().get("first_prompt");
            assertThat(folded).as(text).isEqualTo(FirstPrompt.extractFromHead(head(user(text), user("fallthrough"))));
        }
    }
}
